ages.append(ages[-2])

ages.sort()

print("New ages list after adding min and max ages:", ages)


median_age = (ages[len(ages)//2] + ages[len(ages)//2 - 1]) / 2
print("Median age:", median_age)

avg_age = sum(ages)/ len(ages)
print("Average age:", avg_age)


range_age = ages[-1] - ages[0]
print("Range of ages:", range_age)

abs_diff_min_avg = abs(ages[0] - avg_age)
abs_diff_max_avg = abs(ages[-1] - avg_age)
print("Absolute difference between minimum age and average age:", abs_diff_min_avg)
print("Absolute difference between maximum age and average age:", abs_diff_max_avg)





